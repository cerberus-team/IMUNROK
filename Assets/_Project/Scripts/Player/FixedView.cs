using UnityEngine;

namespace IMUNROK.Common
{
    /// <summary>
    /// <b>이 씬은 고개를 따라 돌지 않는다 — 머리는 못 박고 손만 준다.</b>
    ///
    /// 어전은 <b>연출</b>이다. 왕이 발 너머에서 어명을 내리고 봉서 셋이 어도를 따라
    /// 굴러 내려오는 그림은, 카메라가 어디를 보고 있느냐까지 정해 두고 짠 것이다.
    /// 헤드셋을 쓰면 그 자리가 사람의 목에 넘어가서 — 어명이 흐르는 동안 천장을
    /// 보고 있거나 봉서가 굴러오는 것을 등지고 있어도 게임은 아무 말이 없다.
    ///
    /// 그렇다고 <b>손까지 뺏으면 안 된다</b>. 헤드셋에는 자판도 마우스도 없어서,
    /// 손이 없으면 넘기기 단추도 봉서도 누를 수가 없다 — 앉아서 보는 수밖에 없는
    /// 화면이 된다. 그래서 이 표가 있는 씬에서는:
    ///
    ///   · <b>카메라를 옮기지 않는다</b> — 씬에 짜 둔 자리와 각 그대로. 머리 자세를
    ///     넣는 <c>XRPose</c> 도 안 붙인다. 두 눈으로 갈려 보일 뿐 그림은 고정이다.
    ///   · <b>손 둘은 짓는다</b> — 컨트롤러 광선으로 단추도 봉서도 그대로 누른다.
    ///   · <b>걷지 않는다</b> — 어전에서 스틱으로 돌아다닐 일이 없다.
    ///
    /// 붙이는 곳: 그 씬의 아무 오브젝트에나 하나. <see cref="VRRig"/> 가 씬이 열릴 때
    /// 이것을 찾아 본다. 값이 없다 — 있느냐 없느냐가 전부다.
    /// </summary>
    public class FixedView : MonoBehaviour
    {
        /// <summary>지금 씬이 고정 화면인가.</summary>
        public static bool Here
        {
            get
            {
                return FindFirstObjectByType<FixedView>(FindObjectsInactive.Exclude) != null;
            }
        }
    }
}
