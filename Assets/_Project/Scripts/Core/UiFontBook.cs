using UnityEngine;

namespace IMUNROK.Common
{
    /// <summary>
    /// <b>이 게임의 글씨를 한 장에 적어 둔다.</b>
    ///
    /// <see cref="UiFont"/> 는 여태 <b>선착순</b>이었다 — 폰트를 가진 부품이 먼저
    /// 올리면 나머지가 가져다 쓰는 방식. 표제가 있는 어전에서는 표제가 첫 프레임에
    /// 올려 주니 문제가 없었지만, <b>표제가 없는 씬</b>(사건 현장·관아)에서 먼저
    /// 뜨는 판은 아무도 올리기 전에 물어보게 된다. 그때 돌아가는 것이 유니티
    /// 기본 글씨(LegacyRuntime)인데, 여기에는 <b>한글도 한자도 없다</b>. 그러면
    /// 운영체제가 글자마다 대신할 얼굴을 주워 오므로 — 한글은 이 얼굴, 한자는
    /// 저 얼굴 — 한 줄 안에 필체가 섞인다. "한글 중간에 한자만 딴 글씨체"는
    /// 그렇게 생긴다. 폰트가 <b>없어서</b>가 아니라 <b>아직 안 올라와서</b>다.
    ///
    /// 그래서 Resources 에 한 장 두고, 아무도 안 올렸으면 여기서 집어 온다.
    /// 씬 순서와 상관이 없어진다.
    ///
    /// <b>이 파일은 배선이고 글씨는 아트다.</b> .asset 은 git 에 들어가지만 폰트
    /// 파일 자체는 공유 폴더에 있다. 폰트가 없는 clone 에서는 이 참조가 비어
    /// 있을 뿐, 없다고 터지지는 않는다.
    ///
    /// 만드는 곳: [이문록 ▸ 글씨 ▸ 글씨 한 장 맞추기]
    /// </summary>
    public class UiFontBook : ScriptableObject
    {
        /// <summary>Resources 안에서의 이름. 코드와 도구가 같은 이름을 봐야 한다.</summary>
        public const string ResourceName = "이문록_글씨";

        [Tooltip("한글과 한자를 <b>한 얼굴로</b> 그리는 글씨. 조선백년체는 둘 다 가지고 있다")]
        public Font korean;
    }
}
