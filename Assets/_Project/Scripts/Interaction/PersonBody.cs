using UnityEngine;

namespace IMUNROK.Common
{
    /// <summary>
    /// <b>사람에게 몸을 준다</b> — 지나가지 못하게.
    ///
    /// 마당의 사람들에게는 <b>단단한 콜라이더가 하나도 없었다</b>. 붙어 있는 것은 죄
    /// 트리거뿐이고, 그것은 <b>누르라고</b> 둔 것이지 막으라고 둔 것이 아니다.
    /// 그래서 마을사람도 마름도 옹덕구도 <b>몸을 통과해 걸어 지나갈 수 있었다</b>.
    /// 남의 집을 몰래 뒤지는 이야기에서 사람이 안개면, 들킬 걱정이 반쯤 사라진다.
    ///
    /// <b>왜 트리거를 단단하게 바꾸지 않는가</b>: 그 트리거는 크기와 자리가 <b>누르기
    /// 좋게</b> 맞춰져 있다(넉넉하고, 머리 위까지 덮는다). 그것을 그대로 벽으로 쓰면
    /// 사람 둘레 한 뼘 밖에서부터 막힌다. 누르는 자리와 막는 자리는 <b>다른 크기</b>라야 한다.
    /// 그래서 막는 몸을 <b>따로</b> 하나 더 둔다.
    ///
    /// <b>이 표식이 하는 일</b>은 두 가지다.
    ///   · 이 콜라이더가 <b>사람의 몸</b>임을 알린다.
    ///   · 소리를 듣는 쪽(<see cref="NoiseListener"/>)이 이것을 <b>벽으로 세지 않게</b> 한다.
    ///     저쪽 주석에 이미 「사람은 벽이 아니다」라고 적혀 있었는데, 정작 코드는 아무
    ///     콜라이더나 벽으로 세고 있었다. 사람에게 몸을 주는 순간 그 말이 거짓이 된다 —
    ///     마름이 앞을 지나간다고 서랍 소리가 안 들려서는 안 된다.
    ///
    /// 누르는 것은 그대로 된다. 짚는 쪽이 <c>GetComponentInParent</c> 로 올라가 찾으므로,
    /// 몸을 자식으로 달아도 사람이 짚힌다.
    /// </summary>
    public class PersonBody : MonoBehaviour
    {
        /// <summary>이 콜라이더가 사람의 몸인가. 소리·시선이 물어본다.</summary>
        public static bool Is(Collider c)
        {
            return c != null && c.GetComponentInParent<PersonBody>() != null;
        }
    }
}
